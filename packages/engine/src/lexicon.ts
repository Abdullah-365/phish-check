export interface Rule {
  group: Group;
  label: string;
  pattern: RegExp;
}

const word = (alternatives: string[]) => new RegExp(`(?<![\\p{L}\\p{N}])(?:${alternatives.join("|")})(?![\\p{L}\\p{N}])`, "giu");

const rule = (group: Group, label: string, alternatives: string[]): Rule => ({ group, label, pattern: word(alternatives) });

